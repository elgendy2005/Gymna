import type {
  Contraindication,
  ExerciseEquipment,
  MovementPattern,
  Requirement,
} from "../../../src/lib/exercise-options";
import type { Level } from "../../../src/lib/profile-options";

/**
 * The curated core set: the exercises the program engine may put in a plan.
 * Each one is a free-exercise-db entry (`slug` is its dataset id) with a
 * movement pattern, an Arabic name and Arabic cues. Mistakes, breathing and
 * the pattern-wide health tags come from patterns.ts.
 */
export type CuratedExercise = {
  slug: string;
  pattern: MovementPattern;
  nameAr: string;
  /** Arabic step-by-step cues, in order. */
  cuesAr: string[];
  /** English steps, only for the few entries the dataset ships without any. */
  cuesEn?: string[];
  /** Kit needed beyond the main equipment. */
  requires?: Requirement[];
  /** Health tags on top of the pattern's own. */
  avoid?: Contraindication[];
  /** Overrides for dataset values that are wrong or too coarse. */
  equipment?: ExerciseEquipment;
  difficulty?: Level;
};

type Options = Pick<
  CuratedExercise,
  "cuesEn" | "requires" | "avoid" | "equipment" | "difficulty"
>;

function group(
  pattern: MovementPattern,
  entries: [slug: string, nameAr: string, cuesAr: string[], options?: Options][],
): CuratedExercise[] {
  return entries.map(([slug, nameAr, cuesAr, options]) => ({
    slug,
    pattern,
    nameAr,
    cuesAr,
    ...options,
  }));
}

